"""Paper identity and metadata, synchronised from papers.csv + the acquisition manifest.

The CSV defines the canonical list and order of papers; the manifest (generated by the
retrieval pipeline, schema_version 1) adds bibliographic metadata and the local PDF path.
Neither source file is ever modified. Reviewer data (decisions, notes, evidence) is keyed
by paper_id in separate tables, so re-syncing after the manifest is regenerated never
touches it. Papers that disappear from the sources are flagged (in_source = 0), not deleted.
"""
from __future__ import annotations

import csv
import hashlib
import json
import logging
from pathlib import Path
from typing import Any

from .config import Settings
from .db import Database, dumps, now_iso

log = logging.getLogger(__name__)

SUPPORTED_MANIFEST_SCHEMAS = {1}


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _clean(v: Any) -> Any:
    if isinstance(v, str):
        v = v.strip()
        return v or None
    return v


def read_csv(path: Path) -> tuple[list[str], list[dict[str, str]]]:
    with open(path, encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = [dict(r) for r in reader]
        return list(reader.fieldnames or []), rows


def _csv_get(row: dict[str, str], *names: str) -> str | None:
    lower = {k.lower().strip(): v for k, v in row.items() if k}
    for n in names:
        v = lower.get(n.lower())
        if v is not None and str(v).strip():
            return str(v).strip()
    return None


def read_manifest(path: Path) -> dict[str, dict[str, Any]]:
    if not path.exists():
        log.warning("Manifest not found at %s; continuing with CSV metadata only", path)
        return {}
    with open(path, encoding="utf-8-sig") as f:
        data = json.load(f)
    version = data.get("schema_version")
    if version not in SUPPORTED_MANIFEST_SCHEMAS:
        log.warning("Manifest schema_version %r is not explicitly supported; reading known fields only", version)
    return {p["paper_id"]: p for p in data.get("papers", []) if p.get("paper_id")}


def sync_papers(db: Database, settings: Settings) -> dict[str, int]:
    """Upsert paper metadata from CSV + manifest. Returns counts."""
    fieldnames, rows = read_csv(settings.papers_csv)
    manifest = read_manifest(settings.manifest)
    seen: set[str] = set()
    ts = now_iso()
    order = 0
    with db.tx() as conn:
        for row in rows:
            pid = _csv_get(row, "Paper_ID", "paper_id", "id")
            if not pid or pid in seen:
                continue
            seen.add(pid)
            order += 1
            m = manifest.get(pid, {})
            pdf_path: Path | None = None
            if m.get("pdf_path"):
                p = Path(m["pdf_path"])
                pdf_path = p if p.is_absolute() else settings.root / p
            # A manually added, conventionally named PDF is valid even when an older
            # manifest entry exists without pdf_path (for example, after a reviewer
            # obtains a formerly paywalled paper). It also acts as a fallback when a
            # stale manifest path no longer exists. Explicit, valid manifest paths
            # still take precedence so duplicates and custom locations keep working.
            candidate = settings.pdf_dir / f"{pid}.pdf"
            if (pdf_path is None or not pdf_path.is_file()) and candidate.is_file():
                pdf_path = candidate
            exists = bool(pdf_path and pdf_path.is_file())
            pdf_sha = None
            checksum_ok = None
            stat_key = None
            if exists:
                prev = conn.execute("SELECT pdf_stat, pdf_sha256 FROM papers WHERE paper_id=?", (pid,)).fetchone()
                st = pdf_path.stat()
                stat_key = f"{pdf_path}|{st.st_size}|{int(st.st_mtime)}"
                if prev and prev["pdf_sha256"] and prev["pdf_stat"] == stat_key:
                    pdf_sha = prev["pdf_sha256"]
                else:
                    pdf_sha = sha256_file(pdf_path)
                expected = _clean(m.get("checksum_sha256"))
                checksum_ok = None if not expected else int(expected.lower() == pdf_sha)
            rel_pdf = None
            if pdf_path:
                try:
                    rel_pdf = str(pdf_path.relative_to(settings.root)).replace("\\", "/")
                except ValueError:
                    rel_pdf = str(pdf_path)
            rec = {
                "paper_id": pid,
                "source_order": order,
                "title": _clean(m.get("title")) or _csv_get(row, "Paper_Title", "title"),
                "authors": _clean(m.get("authors")) or _csv_get(row, "authors"),
                "year": str(m["year"]) if m.get("year") else _csv_get(row, "year"),
                "doi": _clean(m.get("doi")) or _csv_get(row, "DOI"),
                "link": _csv_get(row, "Link", "url"),
                "pmid": _clean(m.get("pmid")),
                "pmcid": _clean(m.get("pmcid")),
                "pdf_path": str(pdf_path) if pdf_path else None,
                # size/mtime key so unchanged files are not re-hashed on every start
                "pdf_stat": stat_key if exists else None,
                "pdf_url": _clean(m.get("pdf_url")),
                "landing_page_url": _clean(m.get("landing_page_url")),
                "source": _clean(m.get("source")),
                "access_status": _clean(m.get("access_status")) or ("downloaded" if exists else "unknown"),
                "license": _clean(m.get("license")),
                "checksum_sha256": _clean(m.get("checksum_sha256")),
                "match_confidence": m.get("match_confidence"),
                "duplicate_of": _clean(m.get("duplicate_of")),
                "manifest_notes": _clean(m.get("notes")),
                "pdf_exists": int(exists),
                "pdf_sha256": pdf_sha,
                "pdf_checksum_ok": checksum_ok,
                "csv_json": dumps({"fieldnames": fieldnames, "row": row, "rel_pdf": rel_pdf}),
                "manifest_json": dumps(m) if m else None,
                "synced_at": ts,
            }
            cols = ", ".join(rec)
            placeholders = ", ".join(f":{k}" for k in rec)
            updates = ", ".join(f"{k}=excluded.{k}" for k in rec if k != "paper_id")
            conn.execute(
                f"INSERT INTO papers({cols}, in_source) VALUES({placeholders}, 1) "
                f"ON CONFLICT(paper_id) DO UPDATE SET {updates}, in_source=1",
                rec,
            )
        if seen:
            conn.execute(
                f"UPDATE papers SET in_source=0 WHERE paper_id NOT IN ({','.join('?' * len(seen))})",
                tuple(seen),
            )
    db.set_meta("csv_fieldnames", dumps(fieldnames))
    db.set_meta("last_sync", ts)
    total = db.one("SELECT COUNT(*) n FROM papers WHERE in_source=1")["n"]
    with_pdf = db.one("SELECT COUNT(*) n FROM papers WHERE in_source=1 AND pdf_exists=1")["n"]
    log.info("Synced %d papers (%d with local PDF)", total, with_pdf)
    return {"papers": total, "with_pdf": with_pdf, "manifest_entries": len(manifest)}


def pdf_file_path(paper: dict[str, Any]) -> Path | None:
    if not paper.get("pdf_exists") or not paper.get("pdf_path"):
        return None
    return Path(paper["pdf_path"])
